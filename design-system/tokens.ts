export function readTokens() {
  const styles = getComputedStyle(document.documentElement);
  return Object.fromEntries(
    Object.entries(tokenGroups).map(([group, tokens]) => [
      group,
      Object.fromEntries(
        tokens.map((name) => [
          `--nova-${name}`,
          styles.getPropertyValue(`--nova-${name}`).trim(),
        ]),
      ),
    ]),
  );
}
